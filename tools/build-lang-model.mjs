// Generates lang-model.js: a trimmed copy of the eld n-gram database
// (Latin-script languages only) plus a minimal scorer, loaded as a plain
// script before content-script.js. Usage: node tools/build-lang-model.mjs [size]
//
// eld © 2023 Nito T.M., Apache-2.0 — https://github.com/nitotm/efficient-language-detector-js
import fs from 'fs';
import path from 'path';
import { fileURLToPath } from 'url';

const size = process.argv[2] || 'extrasmall';
const root = path.dirname(path.dirname(fileURLToPath(import.meta.url)));
const eldSrc = path.join(root, 'node_modules/eld/src');
const { ngramsData } = await import(path.join(eldSrc, 'ngrams', `${size}.js`));
const { dictionary } = await import(path.join(eldSrc, 'dictionary.js'));
const { avgScore } = await import(path.join(eldSrc, 'avgScore.js'));

// Scripts other than Latin are settled by regex in content-script.js, so
// only Latin-script languages are kept. The non-target ones matter: they
// are what lets a Portuguese or Catalan title lose to its own language
// instead of being scored as Spanish or French.
// en/es/fr are what gets selected; ca, it, pt, ro, de, nl are what es/fr get
// confused with; pl, sl, sv, tl soak up proper nouns and names. Dropping the
// rest of eld's Latin languages halves the file with no accuracy change on
// tests/lang-eval. Override with LANGS=xx,yy,... to experiment.
const LANGS = process.env.LANGS ? process.env.LANGS.split(',')
  : ['ca', 'de', 'en', 'es', 'fr', 'it', 'nl', 'pl', 'pt', 'ro', 'sl', 'sv', 'tl'];

const oldIds = Object.entries(ngramsData.languages).filter(([, code]) => LANGS.includes(code));
const remap = new Map(oldIds.map(([id], i) => [Number(id), i]));
const codes = oldIds.map(([, code]) => code);

// Each n-gram becomes "id:score,id:score"; scores are already integers.
const ngrams = {};
for (const [gram, byLang] of Object.entries(ngramsData.ngrams)) {
  const kept = Object.entries(byLang)
    .filter(([id]) => remap.has(Number(id)))
    .map(([id, score]) => `${remap.get(Number(id)).toString(36)}:${score.toString(36)}`);
  if (kept.length) ngrams[gram] = kept.join(',');
}

const out = `/* Generated by tools/build-lang-model.mjs (eld ${size}, ${codes.length} languages) — do not edit.
 * N-gram data and scoring from eld © 2023 Nito T.M., Apache-2.0,
 * https://github.com/nitotm/efficient-language-detector-js */
(() => {
  const CODES = ${JSON.stringify(codes)};
  const AVG = ${JSON.stringify(codes.map((c) => avgScore[c]))};
  const DICT = ${JSON.stringify(dictionary)};
  // Kept as one JSON string (cheapest to parse at page load); an n-gram's
  // "id:score,..." entry is only decoded when a title actually contains it.
  const RAW = JSON.parse(${JSON.stringify(JSON.stringify(ngrams))});
  let SEPARATORS;
  try { SEPARATORS = /[^\\p{L}]+(?<![\\x27\\x60\\u2019])/gu; } catch (e) { SEPARATORS = /[^\\p{L}]+/gu; }

  // UTF-8 bytes mapped through eld's dictionary, split into words.
  const toByteWords = (text) => {
    const words = [];
    let word = '';
    for (let i = 0; i < text.length; i++) {
      let c = text.charCodeAt(i);
      if (c < 0x80) {
        if (c === 32) { if (word) words.push(word); word = ''; } else word += text[i];
      } else if (c < 0x800) {
        word += DICT[0xc0 | (c >> 6)] + DICT[0x80 | (c & 0x3f)];
      } else if (c < 0xd800 || c >= 0xe000) {
        word += DICT[0xe0 | (c >> 12)] + DICT[0x80 | ((c >> 6) & 0x3f)] + DICT[0x80 | (c & 0x3f)];
      } else {
        i++;
        c = 0x10000 + (((c & 0x3ff) << 10) | (text.charCodeAt(i) & 0x3ff));
        word += DICT[0xf0 | (c >> 18)] + DICT[0x80 | ((c >> 12) & 0x3f)] + DICT[0x80 | ((c >> 6) & 0x3f)] + DICT[0x80 | (c & 0x3f)];
      }
    }
    if (word) words.push(word);
    return words;
  };

  // Returns { ranked: [[code, score 0-1], ...] best first, ngrams, avg(code) }.
  const score = (text) => {
    const words = toByteWords(text.slice(0, 400).replace(SEPARATORS, ' ').trim().toLowerCase());
    const grams = new Set();
    for (const word of words) {
      const len = Math.min(word.length, 70);
      let j = 0;
      for (; j + 4 < len; j += 3) grams.add((j === 0 ? ' ' : '') + word.substring(j, j + 4));
      grams.add((j === 0 ? ' ' : '') + word.substring(len !== 3 ? len - 4 : 0) + ' ');
    }
    const totals = new Array(CODES.length).fill(0);
    for (const gram of grams) {
      const entry = RAW[gram];
      if (!entry) continue;
      for (const pair of entry.split(',')) {
        const colon = pair.indexOf(':');
        totals[parseInt(pair.slice(0, colon), 36)] += parseInt(pair.slice(colon + 1), 36) + 53;
      }
    }
    const n = grams.size || 1;
    const ranked = [];
    totals.forEach((t, id) => {
      if (t > 0) { const r = t / n; ranked.push([CODES[id], r / (r + 25), AVG[id]]); }
    });
    ranked.sort((a, b) => b[1] - a[1]);
    return { ranked, ngrams: grams.size };
  };

  globalThis.__ytlfLangModel = { score };
})();
`;
fs.writeFileSync(path.join(root, 'lang-model.js'), out);
console.log(`lang-model.js: ${(out.length / 1024).toFixed(0)} KB, ${Object.keys(ngrams).length} n-grams, ${codes.length} languages`);
